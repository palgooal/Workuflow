                <h3 id="data-collected-excluded">2.6 بيانات لا نجمعها</h3>
                <p><strong>لا نجمع ولا نخزّن</strong>: أرقام البطاقات المصرفية، رمز التحقق (CVV)، أرقام الحسابات البنكية أو IBAN، أرقام الهوية الوطنية أو الرقم الضريبي لك أو لعملائك، أو أي بيانات صحية أو دينية أو عرقية أو أي بيانات "فئة خاصة" حساسة قانونياً. لا يوجد في تصميم المنصة أي حقل مخصَّص لجمع هذا النوع من البيانات.</p>

                <h2 id="data-usage">3. كيف نستخدم بياناتك</h2>
