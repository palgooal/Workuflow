                <h2 id="intro">1. مقدّمة وتحديد الأطراف</h2>
                <p>هذه الوثيقة تشرح كيفية جمع بياناتك الشخصية ومعالجتها وحمايتها عند استخدامك لمنصة <strong>دراهم | مال وأعمال</strong> ("<strong>دراهم</strong>" أو "<strong>المنصة</strong>").</p>
                <p>دراهم منتج برمجي مملوك ومُطوَّر ومُشغَّل بالكامل من قِبل <strong>شركة بال قوول لتكنولوجيا المعلومات والدعاية والإعلان</strong> ("<strong>الشركة</strong>" أو "<strong>نحن</strong>")، وهي الجهة الاعتبارية المسؤولة قانونياً عن كل ما يرد في هذه السياسة. أينما وردت عبارة "نحن" أو "الشركة" في هذه الوثيقة، فالمقصود بها شركة بال قوول لتكنولوجيا المعلومات والدعاية والإعلان، وليس "دراهم" ككيان مستقل — فدراهم هو اسم المنتج فقط، وليس شخصية اعتبارية منفصلة عن الشركة المالكة له.</p>
                <p>باستخدامك لمنصة دراهم، فإنك توافق على الممارسات الموصوفة في هذه السياسة. إن لم توافق عليها، يُرجى عدم استخدام المنصة.</p>

                <h2 id="data-collected">2. البيانات التي نجمعها</h2>

                <h3 id="data-collected-account">2.1 عند إنشاء حساب</h3>
                <p>عند التسجيل في دراهم، نجمع منك: <strong>الاسم الكامل</strong>، <strong>البريد الإلكتروني</strong>، <strong>رقم الهاتف</strong> (بصيغة دولية)، <strong>كلمة المرور</strong> (تُخزَّن مُشفَّرة ولا نطّلع على قيمتها الأصلية أبداً)، والعملة الافتراضية التي تختارها لإدارة حساباتك.</p>
                <p>نقوم أيضاً بتسجيل <strong>عنوان IP</strong> و<strong>معرّف المتصفح/الجهاز (User-Agent)</strong> تلقائياً عند التسجيل وعند كل عملية تسجيل دخول لاحقة، وذلك لأغراض أمنية ولمنع إساءة الاستخدام (حسابات وهمية، محاولات اختراق).</p>

                <h3 id="data-collected-clients">2.2 بيانات عملائك التي تُدخلها بنفسك</h3>
                <p>عند استخدامك لدراهم لإدارة عملائك (نظام إدارة علاقات العملاء/CRM)، أو لإصدار فواتير وعروض أسعار، فإنك أنت من يُدخل بيانات هؤلاء العملاء (الاسم، البريد، الهاتف، اسم الشركة، العنوان، ملاحظات، إلخ). <strong>أنت المسؤول الوحيد عن مشروعية جمع هذه البيانات وعن الحصول على أي موافقة قانونية لازمة من عملائك قبل إدخالها في النظام.</strong> تعمل الشركة هنا فقط بصفتها معالجاً تقنياً لهذه البيانات نيابة عنك، وليست هي من يجمعها مباشرة من عملائك.</p>
                <p>عند قبول أو رفض عميلك لعرض سعر عبر رابط عام مُرسَل له، نُسجّل تلقائياً عنوان IP الخاص به كدليل توثيقي على عملية القبول/الرفض.</p>

                <h3 id="data-collected-financial">2.3 البيانات المالية داخل حسابك</h3>
                <p>الفواتير، العروض، المعاملات المالية (دخل/مصروف)، الصناديق (Wallets)، الميزانيات، والديون التي تُدخلها بنفسك ضمن استخدامك اليومي للمنصة. هذه البيانات مُخصَّصة لك وحدك، ومعزولة تقنياً بحيث لا يمكن لأي مستخدم آخر على المنصة الاطّلاع عليها.</p>

                <h3 id="data-collected-payments">2.4 بيانات مدفوعات الاشتراك وتحصيل فواتير عملائك</h3>
                <p>عند دفع اشتراكك في دراهم، أو عند استخدام ميزة تحصيل مدفوعات فواتيرك من عملائك إلكترونياً، تتم عملية الدفع الفعلية على صفحة بوابة الدفع <strong>Togo (togo.ps)</strong>، التي نتعاقد معها لهذا الغرض. <strong>لا تصل بيانات بطاقتك المصرفية أو حسابك البنكي إلى خوادم دراهم أبداً</strong> — دراهم لا يستقبل ولا يخزّن أرقام البطاقات أو رمز التحقق (CVV) أو أي بيانات مصرفية كاملة بأي شكل. ما تستقبله بوابة الدفع منّا لإتمام العملية هو: بريدك الإلكتروني (أو بريد عميلك الدافع)، الاسم، رقم الهاتف، المدينة والدولة (لإنشاء ملف مستلم الدفع لدى Togo)، والمبلغ والعملة.</p>

                <h3 id="data-collected-cookies">2.5 ملفات تعريف الارتباط (Cookies)</h3>
