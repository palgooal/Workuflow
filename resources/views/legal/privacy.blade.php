                    <li><strong>البنية البريدية الداخلية</strong> — رسائل النظام والفواتير تُرسَل عبر خادم البريد الخاص بالمنصة، والذي تُديره شركة بال قوول لتكنولوجيا المعلومات والدعاية والإعلان مباشرةً، دون استخدام أي خدمة بريد إلكتروني خارجية.</li>
