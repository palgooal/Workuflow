                <h2 id="otp">6. التحقق من الهوية (OTP)</h2>
                <p>لا تستخدم المنصة حالياً أي رمز تحقق (OTP) عبر رسالة نصية أو واتساب أو بريد إلكتروني للتحقق من ملكيتك الفعلية لرقم الهاتف أو البريد الإلكتروني الذي تُدخله. يُتحقق فقط من صيغة رقم الهاتف وتفرّده داخل قاعدة بياناتنا، ومن ملكية البريد الإلكتروني عبر رابط تحقق يُرسَل إليه. عند تفعيل التحقق برمز OTP مستقبلاً (يُخطَّط لتفعيله عبر WhatsApp Business Platform)، سنُحدّث هذا القسم ليصف الآلية الفعلية بدقة.</p>

                <h2 id="security">7. أمن البيانات</h2>
                <p>نتخذ إجراءات معقولة لحماية بياناتك، من بينها:</p>
                <ul>
                    <li>تشفير كلمات المرور بخوارزمية bcrypt أحادية الاتجاه — لا نطّلع نحن ولا أي طرف آخر على كلمة مرورك الفعلية.</li>
                    <li>عزل بيانات كل حساب تقنياً بحيث لا يمكن لمستخدم آخر الوصول إلى بياناتك حتى لو حاول تخمين معرّفات السجلات.</li>
                    <li>أنظمة حماية من محاولات إنشاء حسابات آلية (بوتات) ومن محاولات الدخول المتكررة غير المشروعة.</li>
                    <li>نقل البيانات عبر اتصال مشفَّر (HTTPS) بين جهازك وخوادمنا.</li>
                </ul>
                <p>مع ذلك، لا يمكن لأي نظام أن يضمن أماناً مطلقاً بنسبة 100%، ونعمل باستمرار على تطوير إجراءات الحماية لدينا.</p>

